#!/usr/bin/env bash
# imprint Docker dev environment helper.
# Usage: docker/dev.sh {build|up|shell|save|stop|down|destroy|status|nds|wasm|test}
set -euo pipefail

# -P: physical resolution. This script is reachable through the
# ~/workspace/docker -> imprint/docker symlink; bash `cd` defaults to logical
# (-L), which would make dirname/.. stop at ~/workspace and turn compose's
# `- ..:/workspace/imprint` bind into a whole-workspace mount over the repo.
ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="$ROOT/docker/compose.yaml"
# Generated override: run the container as root (image default is `USER dev`).
# `docker compose up` has no --user flag, so root goes in via a second -f file.
# Lives under build/ (gitignored) — regenerated by compose() on every call.
COMPOSE_ROOT_OVERRIDE="$ROOT/build/docker/compose.root.yaml"
PROJECT="imprint-dev"
CONTAINER="imprint-dev"
MELODS_HOST="${MELODS_HOST:-$ROOT/../melonDS-x86_64.AppImage}"
if [ ! -f "$MELODS_HOST" ]; then
    MELODS_HOST="/home/bing/workspace/melonDS-x86_64.AppImage"
fi

# The optional fps sibling-repo bind (see compose.yaml): pointing the
# container at a directory that does not exist makes compose create an
# empty root-owned one, so the bind only materializes when the host
# actually has the repo (or when IMPRINT_DEV_WITH_FPS=1 forces it, e.g.
# to see the compose error for a misconfigured path).
if [ "${IMPRINT_DEV_WITH_FPS:-0}" = "1" ] || [ -d "${HOME}/workspace/fps" ]; then
    export IMPRINT_DEV_FPS_BIND="${HOME}/workspace/fps"
else
    export IMPRINT_DEV_FPS_BIND=/dev/null
fi

compose() {
    # UID is a bash readonly (always set); GID must be derived
    # XAUTHORITY_FILE: X cookie path for the container mount
    export GID
    GID="$(id -g)"
    export XAUTHORITY_FILE="${XAUTHORITY:-${HOME}/.Xauthority}"
    if [ -n "${XAUTHORITY:-}" ] && [ -f "$XAUTHORITY" ]; then
        XAUTHORITY_FILE="$XAUTHORITY"
    fi
    # GDM often uses /run/user/.../gdm/Xauthority
    if [ ! -f "$XAUTHORITY_FILE" ] && [ -f "/run/user/$(id -u)/gdm/Xauthority" ]; then
        XAUTHORITY_FILE="/run/user/$(id -u)/gdm/Xauthority"
    fi
    if [ ! -f "$XAUTHORITY_FILE" ]; then
        XAUTHORITY_FILE="/tmp/imprint-empty-xauth"
        : >"$XAUTHORITY_FILE"
    fi
    export XAUTHORITY_FILE

    # root user override (image default: USER dev) — always rewrite so a stale
    # file can never hide the current intent
    mkdir -p "$(dirname "$COMPOSE_ROOT_OVERRIDE")"
    cat >"$COMPOSE_ROOT_OVERRIDE" <<'YAML'
# generated by docker/dev.sh — do not edit
services:
  dev:
    user: "0:0"
YAML

    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" -f "$COMPOSE_ROOT_OVERRIDE" "$@"
}

# Is the existing container already configured to run as root?
container_is_root() {
    case "$(docker inspect -f '{{.Config.User}}' "$CONTAINER" 2>/dev/null || true)" in
    0 | 0:* | root | root:*) return 0 ;;
    *) return 1 ;;
    esac
}

stage_melonds() {
    local dest="$ROOT/docker/context/melonDS-x86_64.AppImage"
    mkdir -p "$ROOT/docker/context"
    if [ -f "$MELODS_HOST" ]; then
        if [ ! -f "$dest" ] || [ "$MELODS_HOST" -nt "$dest" ]; then
            cp -f "$MELODS_HOST" "$dest"
            echo "staged melonDS -> docker/context/"
        fi
    elif [ ! -f "$dest" ]; then
        echo "error: melonDS AppImage not found at $MELODS_HOST" >&2
        echo "       set MELODS_HOST=/path/to/melonDS-x86_64.AppImage" >&2
        exit 1
    fi
}

allow_x() {
    # Allow local clients (same user) to talk to the host X server.
    # Container user may differ (dev/root vs host user) — grant each when possible.
    if command -v xhost >/dev/null 2>&1 && [ -n "${DISPLAY:-}" ]; then
        xhost +local: >/dev/null 2>&1 || true
        xhost +SI:localuser:$(id -un) >/dev/null 2>&1 || true
        xhost +SI:localuser:dev >/dev/null 2>&1 || true
        xhost +SI:localuser:root >/dev/null 2>&1 || true
    fi
}

# dsh inside the container reaches the host's Magpie gateway through host
# networking (127.0.0.1:3425 is the host loopback), so it needs the same
# provider/default-model layer the host uses. The profile patch and the
# gateway key live in the host ~/.dsh; ~/.dsh in the container is the
# persistent dev-home volume, so seeding it here survives stop/restart and
# repairs a fresh volume. The host stays the single source of truth: a model
# switch made in the container UI is overwritten by the next up/shell.
# DSH_PROFILES extends the sync to other profiles (space separated).
sync_dsh_config() {
    local src="${DSH_HOME:-$HOME/.dsh}"
    local home=/root
    local profile patch

    [ "$(docker inspect -f '{{.State.Running}}' "$CONTAINER" 2>/dev/null || true)" = "true" ] || return 0
    container_is_root || home=/home/dev

    if [ ! -f "$src/.env" ] && [ ! -d "$src/profiles" ]; then
        echo "imprint-dev: no host dsh config at $src — container dsh keeps its own" >&2
        return 0
    fi

    docker exec -u root "$CONTAINER" mkdir -p "$home/.dsh/profiles" >/dev/null 2>&1 || return 0
    # gateway key (MAGPIE_GATEWAY_KEY) — local relay, not a real secret
    if [ -f "$src/.env" ]; then
        docker cp "$src/.env" "$CONTAINER:$home/.dsh/.env" >/dev/null 2>&1 || true
    fi
    for profile in ${DSH_PROFILES:-web}; do
        patch="$src/profiles/$profile/cordis.patch.yml"
        [ -f "$patch" ] || continue
        if docker cp "$patch" "$CONTAINER:$home/.dsh/profiles/$profile/cordis.patch.yml" >/dev/null 2>&1; then
            echo "dsh: synced $profile provider config -> $home/.dsh"
        else
            echo "imprint-dev: could not sync $patch — container dsh keeps its own" >&2
        fi
    done
}

cmd="${1:-status}"
shift || true

case "$cmd" in
build)
    stage_melonds
    compose build "$@"
    ;;
up)
    stage_melonds
    allow_x
    # container is long-lived: create if missing, otherwise bring up.
    # `compose up -d` on an existing container is a no-op start when image and
    # config are unchanged, and recreates when they drifted (after `save`, a
    # rebuild, or a compose.yaml change such as a new bind) — so `up` alone
    # always applies. Root (`user: 0:0` override) is a config change: a
    # pre-override container needs recreate too. State kept only inside the
    # old container layer (installed packages) does not survive a recreate —
    # run `dev.sh save` first; the /root named volume always survives.
    if [ -z "$(compose ps -q dev 2>/dev/null || true)" ]; then
        compose up -d "$@"
    elif container_is_root; then
        compose up -d "$@"
    else
        echo "imprint-dev: recreating container to switch user dev -> root" >&2
        echo "             (state not baked into the image is lost)" >&2
        compose up -d "$@"
    fi
    echo "container: $CONTAINER  (shell: docker/dev.sh shell)"
    sync_dsh_config
    ;;
shell)
    allow_x
    sync_dsh_config
    exec docker exec -it -u root "$CONTAINER" bash -l "$@"
    ;;
stop)
    compose stop "$@"
    ;;
# stop + remove container (keeps image + host binds + the /root named volume).
# Data on host and in the dev-home volume is safe; system installs in the
# container layer are NOT — bake them first with `save` or the Dockerfile.
down | destroy)
    compose down "$@"
    ;;
# Bake the current container's writable layer into the image (docker commit):
# apt/npm/pip installs and system-path files made inside the container become
# part of imprint-dev:latest, so the recreate that the next `up` does (image
# changed) comes back WITH them. Anything installed after `save` but before
# that recreate is still lost — save again first. State in /root needs no
# save (named volume).
save)
    docker commit -c 'USER root' "$CONTAINER" "imprint-dev:latest"
    echo "committed $CONTAINER -> imprint-dev:latest"
    echo "next dev.sh up recreates the container from it (kept installs apply)"
    ;;
status)
    compose ps "$@"
    ;;
nds)
    # cross-build ROM inside the container (NDS toolchain is in the image)
    docker exec -u root -w /workspace/imprint "$CONTAINER" \
        sh -c 'cmake -S . -B build/build_nds -DCMAKE_TOOLCHAIN_FILE=cmake/nds.toolchain.cmake && cmake --build build/build_nds "$@"' -- "$@"
    ;;
wasm)
    # demo/wasm/build.sh expects repo at /src (entrypoint symlink)
    docker exec -u root "$CONTAINER" sh -c 'cd /src && sh demo/wasm/build.sh "$@"' -- "$@"
    ;;
    test)
    docker exec -u root -w /workspace/imprint "$CONTAINER" \
        sh -c 'cmake -S . -B build/build_dev && cmake --build build/build_dev -j"$(nproc)" && ./build/build_dev/bin/test_imui && ./build/build_dev/bin/test_zbapi'
    ;;
*)
    echo "usage: $0 {build|up|shell|save|stop|down|destroy|status|nds|wasm|test}" >&2
    exit 2
    ;;
esac
